const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const test = require('node:test')

function readProjectFile(filePath) {
  return fs.readFileSync(path.join(__dirname, '..', filePath), 'utf8')
}

function readRule(content, selector) {
  const escapedSelector = selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  const match = content.match(new RegExp(`${escapedSelector}\\s*\\{([^}]*)\\}`))
  return match ? match[1] : ''
}

test('mine balance band navigates to points page without recharge bubbling', () => {
  const appJson = JSON.parse(readProjectFile('app.json'))
  const indexJs = readProjectFile('pages/index/index.js')
  const indexWxml = readProjectFile('pages/index/index.wxml')

  assert.ok(appJson.pages.includes('pages/points/points'))
  assert.ok(appJson.pages.includes('pages/points-rules/points-rules'))
  assert.match(indexJs, /const POINTS_PAGE_URL = '\/pages\/points\/points'/)
  assert.match(indexJs, /handlePointsTap\(\)[\s\S]*url:\s*POINTS_PAGE_URL/)
  assert.match(indexWxml, /class="balance-band"[\s\S]*bindtap="handlePointsTap"/)
  assert.match(indexWxml, /class="light-button"[\s\S]*catchtap="handleRechargeTap"[\s\S]*>充值</)
})

