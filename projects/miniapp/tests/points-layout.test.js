  const rulesJsonPath = path.join(__dirname, '../pages/points-rules/points-rules.json')
  const rulesWxmlPath = path.join(__dirname, '../pages/points-rules/points-rules.wxml')
  const rulesWxssPath = path.join(__dirname, '../pages/points-rules/points-rules.wxss')

  assert.equal(fs.existsSync(rulesJsPath), true)
  assert.equal(fs.existsSync(rulesJsonPath), true)
  assert.equal(fs.existsSync(rulesWxmlPath), true)
  assert.equal(fs.existsSync(rulesWxssPath), true)

  const rulesJs = fs.readFileSync(rulesJsPath, 'utf8')
  const rulesWxml = fs.readFileSync(rulesWxmlPath, 'utf8')
  const rulesWxss = fs.readFileSync(rulesWxssPath, 'utf8')
  const costGroupRule = readRule(rulesWxss, '.cost-group')
  const costLineRule = readRule(rulesWxss, '.cost-line')
  const giftMarkRule = readRule(rulesWxss, '.cost-mark.gift')
  const giftDescRule = readRule(rulesWxss, '.gift-desc')
  const giftChipRule = readRule(rulesWxss, '.cost-chip.gift')

  assert.match(rulesJs, /const POINT_OVERVIEW_URL = '\/api\/mine\/points'/)
  assert.match(rulesJs, /normalizePointOverview/)
  assert.match(rulesWxml, /navigation-bar title="积分规则" back="\{\{true\}\}"/)
  assert.match(rulesWxml, /section-title">积分具体规则</)
  assert.doesNotMatch(rulesWxml, /acquisition-panel|acquisition-board|section-title">积分获取</)
  assert.match(rulesWxml, /wx:if="\{\{pointData\.ruleGroups\.length \|\| pointData\.acquisitionRules\.length\}\}" class="cost-board"/)
